# define a function that takes parameters
def greet(name, age):
    print("Hello " + name + "! You are " + str(age) + " years old.")


# define a function that returns a value
def add(a, b):
    return a + b


# call the functions with different arguments
greet("Zicheng", 15)
greet("Alex", 16)

total = add(4, 7)
print("4 + 7 =", total)
