# basic string operations
first_name = "Zicheng"
last_name = "Huang"

# concatenation
full_name = first_name + " " + last_name
print("Full name:", full_name)

# slicing
print("First 3 letters:", full_name[0:3])
print("Last name from slicing:", full_name[8:])

# length
print("Length:", len(full_name))
